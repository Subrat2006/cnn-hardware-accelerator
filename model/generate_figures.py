# 2 & 3. CDC timing diagrams (Python behavioral replica of the RTL logic,
#         NOT captured from an RTL/VCD simulation)
# =============================================================================
def fig_cdc_pulse_timing():
    Tsrc, Tdst = 1.0, 0.62   # deliberately non-integer ratio (100 MHz vs ~161 MHz-like ratio)
    dt = 0.002
    t_end = 9.0
    times = np.arange(0, t_end, dt)

    src_clk = ((times % Tsrc) < Tsrc / 2).astype(int)
    dst_clk = ((times % Tdst) < Tdst / 2).astype(int)

    pulse_in = np.zeros_like(times, dtype=int)
    pulse_start, pulse_stop = 2.0, 2.0 + Tsrc  # one src_clk-period-wide pulse
    pulse_in[(times >= pulse_start) & (times < pulse_stop)] = 1

    toggle = np.zeros_like(times, dtype=int)
    sync0 = np.zeros_like(times, dtype=int)
    sync1 = np.zeros_like(times, dtype=int)
    sync2 = np.zeros_like(times, dtype=int)
    pulse_out = np.zeros_like(times, dtype=int)

    cur_toggle = 0
    cur_sync = [0, 0, 0]  # index0=LSB(sync_dst[0]) .. index2=MSB(sync_dst[2])
    prev_src = 0
    prev_dst = 0

    for i in range(len(times)):
        if src_clk[i] == 1 and prev_src == 0:       # posedge src_clk
            if pulse_in[i]:
                cur_toggle ^= 1
        prev_src = src_clk[i]
        toggle[i] = cur_toggle

        if dst_clk[i] == 1 and prev_dst == 0:        # posedge dst_clk
            cur_sync = [cur_toggle, cur_sync[0], cur_sync[1]]
        prev_dst = dst_clk[i]

        sync0[i], sync1[i], sync2[i] = cur_sync
        pulse_out[i] = cur_sync[2] ^ cur_sync[1]

    signals = [
        ("src_clk (AXI, ~100 MHz)", src_clk),
        ("pulse_in (CTRL.start write)", pulse_in),
        ("toggle_src", toggle),
        ("dst_clk (core, different freq)", dst_clk),
        ("sync_dst[0]", sync0),
        ("sync_dst[1]", sync1),
        ("sync_dst[2]", sync2),
        ("pulse_out (1-cycle, core domain)", pulse_out),
    ]

    fig, axes = plt.subplots(len(signals), 1, figsize=(10, 8), sharex=True)
    for ax, (label, sig) in zip(axes, signals):
        ax.step(times, sig, where="post", linewidth=1.4, color="#1f618d")
        ax.set_ylim(-0.3, 1.3)
        ax.set_yticks([0, 1])
        ax.set_ylabel(label, rotation=0, ha="right", va="center", fontsize=8)
        ax.grid(alpha=0.25)
    axes[-1].set_xlabel("time (arbitrary units)")
    fig.suptitle("cdc_pulse_sync.v -- toggle + double-sync + edge-detect\n"
                 "(cycle-level rendering of the RTL update rules)",
                 fontsize=10)
    fig.tight_layout(rect=[0, 0, 1, 0.94])
    fig.savefig(os.path.join(OUT_DIR, "cdc_pulse_timing.png"), dpi=160)
    plt.close(fig)


def fig_cdc_2ff_timing():
    Tdst = 0.7
    dt = 0.002
    t_end = 6.0
    times = np.arange(0, t_end, dt)
    dst_clk = ((times % Tdst) < Tdst / 2).astype(int)

    # an asynchronous "busy" level that changes at a moment NOT aligned to dst_clk
    async_in = np.zeros_like(times, dtype=int)
    async_in[(times >= 1.35)] = 1
    async_in[(times >= 4.1)] = 0

    meta = np.zeros_like(times, dtype=int)
    sync_out = np.zeros_like(times, dtype=int)
    cur_meta, cur_out = 0, 0
    prev_dst = 0
    for i in range(len(times)):
        if dst_clk[i] == 1 and prev_dst == 0:
            cur_out = cur_meta
            cur_meta = async_in[i]
        prev_dst = dst_clk[i]
        meta[i] = cur_meta
        sync_out[i] = cur_out

    signals = [
        ("dst_clk", dst_clk),
        ("async_in (busy, core domain)", async_in),
        ("meta (1st flop)", meta),
        ("sync_out (2nd flop, AXI-safe)", sync_out),
    ]
    fig, axes = plt.subplots(len(signals), 1, figsize=(9, 4.5), sharex=True)
    for ax, (label, sig) in zip(axes, signals):
        ax.step(times, sig, where="post", linewidth=1.4, color="#117864")
        ax.set_ylim(-0.3, 1.3)
        ax.set_yticks([0, 1])
        ax.set_ylabel(label, rotation=0, ha="right", va="center", fontsize=8)
        ax.grid(alpha=0.25)
    axes[-1].set_xlabel("time (arbitrary units)")
    fig.suptitle("cdc_sync_2ff.v -- double-flop level synchronizer\n"
                 "(cycle-level rendering of the RTL update rules)",
                 fontsize=10)
    fig.tight_layout(rect=[0, 0, 1, 0.92])
    fig.savefig(os.path.join(OUT_DIR, "cdc_2ff_timing.png"), dpi=160)
    plt.close(fig)


