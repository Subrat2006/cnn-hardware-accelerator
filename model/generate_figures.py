# 4. Sparsity funnel: raw ReLU sparsity vs. what the NEXT MAC engine sees
# =============================================================================
def fig_sparsity_funnel(inter):
    def sparsity(a):
        return 100.0 * np.sum(a == 0) / a.size

    stages = [
        ("Conv1 output\n(raw ReLU)", sparsity(inter['conv1'])),
        ("Pool1 output\n(seen by Conv2)", sparsity(inter['pool1'])),
        ("Conv2 output\n(raw ReLU)", sparsity(inter['conv2'])),
        ("Pool2 output\n(seen by FC1)", sparsity(inter['pool2'])),
        ("FC1 output\n(seen by FC2,\nno pooling in between)", sparsity(inter['fc1'])),
    ]
    labels = [s[0] for s in stages]
    values = [s[1] for s in stages]
    colors = ["#2e86c1", "#a9cce3", "#2e86c1", "#a9cce3", "#2e86c1"]

    fig, ax = plt.subplots(figsize=(9, 4.5))
    bars = ax.bar(labels, values, color=colors, edgecolor="#154360")
    for b, v in zip(bars, values):
        ax.text(b.get_x() + b.get_width() / 2, v + 1, f"{v:.1f}%", ha="center", fontsize=9)
    ax.set_ylabel("Fraction of exact zeros (%)")
    ax.set_title("Raw ReLU sparsity vs. sparsity actually seen by the next MAC engine\n"
                 "(max pooling suppresses zeros: a 2x2 window is zero only if all 4 inputs are zero)")
    ax.set_ylim(0, max(values) * 1.25)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "sparsity_funnel.png"), dpi=160)
    plt.close(fig)


