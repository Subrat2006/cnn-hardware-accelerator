# 8. PE-count design-space sweep
# =============================================================================
def fig_pe_sweep():
    rows = pe_sweep_rows()
    pes = [r["pe"] for r in rows]
    cycles = [r["cycles"] for r in rows]
    util = [r["util"] for r in rows]
    lanes = [r["lanes"] for r in rows]
    prod = [r["cycles_x_lanes"] / 1e6 for r in rows]

    fig, axs = plt.subplots(1, 3, figsize=(13, 4.2))
    labels = [str(p) for p in pes]
    colors = ["#aab7b8", "#aab7b8", "#2e86c1", "#aab7b8"]

    axs[0].bar(labels, [c / 1000 for c in cycles], color=colors, edgecolor="#1b4f72")
    for i, c in enumerate(cycles):
        axs[0].text(i, c / 1000 + 1.5, f"{c:,}", ha="center", fontsize=8)
    axs[0].set_xlabel("MAC lanes per engine (NUM_PE)")
    axs[0].set_ylabel("Inference cycles (thousands)")
    axs[0].set_title("Latency")

    axs[1].bar(labels, util, color=colors, edgecolor="#1b4f72")
    for i, u in enumerate(util):
        axs[1].text(i, u + 1.5, f"{u:.1f}%", ha="center", fontsize=8)
    axs[1].set_ylim(0, 115)
    axs[1].set_xlabel("MAC lanes per engine (NUM_PE)")
    axs[1].set_ylabel("Average lane utilization (%)")
    axs[1].set_title("Utilization")

    axs[2].bar(labels, prod, color=colors, edgecolor="#1b4f72")
    for i, (v, l) in enumerate(zip(prod, lanes)):
        axs[2].text(i, v + 0.04, f"{v:.2f}M\n({l} lanes)", ha="center", fontsize=8)
    axs[2].set_ylim(0, max(prod) * 1.25)
    axs[2].set_xlabel("MAC lanes per engine (NUM_PE)")
    axs[2].set_ylabel("Cycles x total lanes (millions)")
    axs[2].set_title("Area-delay product")

    fig.suptitle("PE-count design space (selected: 8, highlighted)")
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "pe_sweep.png"), dpi=160)
    plt.close(fig)


