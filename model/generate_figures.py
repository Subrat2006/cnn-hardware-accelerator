def main():
    weights, img = get_weights_and_image()

    scores, inter = forward(img, weights)

    x0 = img.reshape(1, cfg.IMG_H, cfg.IMG_W)
    c1_cycles, c1_mac, c1_skip, _ = conv_layer_cycles_and_macs(x0, weights['conv1_w'], cfg.NUM_PE)
    c2_cycles, c2_mac, c2_skip, _ = conv_layer_cycles_and_macs(inter['pool1'], weights['conv2_w'], cfg.NUM_PE)
    flat = inter['pool2'].flatten()
    fc1_cycles, fc1_mac, fc1_skip = fc_layer_cycles_and_macs(flat, weights['fc1_w'], cfg.NUM_PE)
    fc2_cycles, fc2_mac, fc2_skip = fc_layer_cycles_and_macs(inter['fc1'], weights['fc2_w'], cfg.NUM_PE)

    per_layer = {
        "Conv1": (c1_mac, c1_skip),
        "Conv2": (c2_mac, c2_skip),
        "FC1": (fc1_mac, fc1_skip),
        "FC2": (fc2_mac, fc2_skip),
    }
    total_mac = c1_mac + c2_mac + fc1_mac + fc2_mac
    total_skip = c1_skip + c2_skip + fc1_skip + fc2_skip

    p1c = pool_layer_cycles(cfg.C1_COUT, cfg.P1_OUT_H, cfg.P1_OUT_W)
    p2c = pool_layer_cycles(cfg.C2_COUT, cfg.P2_OUT_H, cfg.P2_OUT_W)
    stage_cycles = {
        "Load": cfg.IMG_H * cfg.IMG_W, "Conv1": c1_cycles, "Pool1": p1c,
        "Conv2": c2_cycles, "Pool2": p2c, "FC1": fc1_cycles, "FC2": fc2_cycles,
    }

    print("Generating figures into docs/images/ (architecture.png is a")
    print("separately maintained diagram and is left untouched) ...")
    fig_cdc_pulse_timing()
    fig_cdc_2ff_timing()
    fig_sparsity_funnel(inter)
    fig_mac_skip_per_layer(per_layer)
    fig_mac_skip_total(total_mac, total_skip)
    fig_pe_utilization()
    fig_pe_sweep()
    fig_latency_breakdown(stage_cycles)
    fig_memory_breakdown()
    print("Done:")
    for f in sorted(os.listdir(OUT_DIR)):
        print("  docs/images/" + f)


if __name__ == "__main__":
    main()
