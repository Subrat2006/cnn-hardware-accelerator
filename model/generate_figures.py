# 9. Per-stage latency breakdown
# =============================================================================
def fig_latency_breakdown(stage_cycles):
    names = list(stage_cycles.keys())
    vals = [stage_cycles[n] for n in names]
    total = sum(vals)
    fig, ax = plt.subplots(figsize=(9, 4.2))
    palette = ["#85c1e9", "#2e86c1", "#f8c471", "#e67e22", "#82e0aa", "#28b463", "#d7bde2"]
    bars = ax.bar(names, vals, color=palette[:len(names)], edgecolor="#333333")
    for b, v in zip(bars, vals):
        ax.text(b.get_x() + b.get_width() / 2, v + total * 0.008,
                f"{v:,}\n({100.0 * v / total:.1f}%)", ha="center", fontsize=8)
    ax.set_ylabel("Core-clock cycles")
    ax.set_ylim(0, max(vals) * 1.2)
    ax.set_title(f"Latency breakdown per stage (total {total:,} cycles)")
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "latency_breakdown.png"), dpi=160)
    plt.close(fig)


