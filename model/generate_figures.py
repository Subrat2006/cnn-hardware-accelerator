"""
generate_figures.py

Generates every figure embedded in README.md EXCEPT architecture.png, from
either (a) the exact same deterministic control-flow model used by
cycle_model.py, or (b) a cycle-level Python behavioral replica of a
specific CDC module's logic (the timing diagrams are cycle-level
renderings of the same state update rules the RTL implements).

docs/images/architecture.png is a separately maintained, hand-crafted
diagram (not generated by this script) -- this script deliberately does
NOT touch it, so re-running this file will never overwrite it.

Run from the model/ directory, after generate_vectors.py:
    python generate_figures.py

Output: docs/images/*.png (except architecture.png)
"""

