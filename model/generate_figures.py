# 7. PE utilization per layer/group
# =============================================================================
def fig_pe_utilization():
    rows = [
        ("Conv1\n(1 group)", [6]),
        ("Conv2\n(2 groups)", [8, 8]),
        ("FC1\n(15 groups)", [8] * 15),
        ("FC2\n(2 groups)", [8, 2]),
    ]
    fig, ax = plt.subplots(figsize=(10, 4.5))
    xpos = 0
    xticks, xticklabels = [], []
    gap = 0.8
    for name, groups in rows:
        start = xpos
        for g in groups:
            pct = 100.0 * g / cfg.NUM_PE
            ax.bar(xpos, pct, color="#28b463" if pct == 100 else "#f5b041", edgecolor="#1e8449", width=0.8)
            xpos += 1
        xticks.append((start + xpos - 1) / 2)
        xticklabels.append(name)
        xpos += gap
    ax.axhline(100, color="#566573", linestyle="--", linewidth=0.8)
    ax.set_xticks(xticks)
    ax.set_xticklabels(xticklabels)
    ax.set_ylabel("Active PE lanes / 8 (%)")
    ax.set_ylim(0, 115)
    ax.set_xlim(-1, xpos)
    ax.set_title("PE-array utilization per layer group\n(green = fully utilized group, orange = partial)")
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "pe_utilization.png"), dpi=160)
    plt.close(fig)


