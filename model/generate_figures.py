# 5. Executed vs skipped MACs per layer (hardware-accurate, from cycle_model)
# =============================================================================
def fig_mac_skip_per_layer(per_layer):
    names = list(per_layer.keys())
    mac = [per_layer[n][0] for n in names]
    skip = [per_layer[n][1] for n in names]

    fig, ax = plt.subplots(figsize=(8, 4.5))
    x = np.arange(len(names))
    ax.bar(x, mac, label="Executed MACs", color="#1f618d")
    ax.bar(x, skip, bottom=mac, label="Zero-gated (skipped)", color="#e67e22")
    for i in range(len(names)):
        total = mac[i] + skip[i]
        pct = 100.0 * skip[i] / total if total else 0
        ax.text(x[i], total + max(mac + skip) * 0.02, f"{pct:.1f}% skipped", ha="center", fontsize=8)
    ax.set_xticks(x)
    ax.set_xticklabels(names)
    ax.set_ylabel("MAC-lane operations")
    ax.set_title("Executed vs. zero-gated MAC operations per layer\n(exact counts, from model/cycle_model.py)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "mac_skip_per_layer.png"), dpi=160)
    plt.close(fig)


